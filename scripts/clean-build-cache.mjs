#!/usr/bin/env node
// Remove the build caches so the next build starts from source only.
//
// WHY THIS EXISTS. On 2026-07-28 a build died ~1,500 pages into prerendering:
//
//   Cannot find module dist/server/.prerender/chunks/content-assets_Dq5R1RbT.mjs
//   imported from dist/server/.prerender/chunks/_astro_content_W5evXr1n.mjs
//
// That chunk is built from .astro/content-assets.mjs. At the time of the
// failure .astro was in a mixed state: content.d.ts and types.d.ts had been
// rewritten by that build, content-assets.mjs was still an hour old, and
// data-store.json was absent entirely. The chunk that went missing is the one
// generated from the stale file. That is a match, not a proof, but a build
// cache holding files from two different runs has no business surviving into a
// release, so the fix is to clear it rather than to reason about it further.
//
// Deliberately NOT wired into `npm run build`. The caches exist to make builds
// fast, and 1,850 pages is not a fast build. Reach for `npm run build:clean`
// when a build fails in a way that does not correspond to a source change, or
// before cutting release evidence, where a clean tree is the point.
//
// Everything removed here is gitignored and regenerated by the next build.
// Nothing in this script can destroy source.

import { rmSync, existsSync, statSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Guard: refuse to run anywhere that is not obviously this project. A bad cwd
// plus a recursive delete is exactly the accident worth spending six lines on.
if (!existsSync(join(root, 'astro.config.mjs')) || !existsSync(join(root, 'src', 'content.config.ts'))) {
  console.error(`Refusing to clean: ${root} does not look like the parent-coach-desk root.`);
  process.exit(1);
}

// Build output and caches only. Every entry here must be gitignored; if you
// add one that is not, this script becomes a way to delete tracked files.
const TARGETS = [
  'dist',                 // build output
  '.astro',               // content collections cache + generated types
  'node_modules/.vite',   // vite dependency pre-bundle
];

let removed = 0;
for (const rel of TARGETS) {
  const abs = join(root, rel);
  if (!existsSync(abs)) {
    console.log(`  skip  ${rel} (absent)`);
    continue;
  }
  const kind = statSync(abs).isDirectory() ? 'dir ' : 'file';
  rmSync(abs, { recursive: true, force: true });
  console.log(`  rm    ${rel} (${kind})`);
  removed += 1;
}

console.log(
  removed === 0
    ? 'Nothing to clean. Caches were already absent.'
    : `Cleaned ${removed} cache location${removed === 1 ? '' : 's'}. The next build rebuilds them from source.`,
);
