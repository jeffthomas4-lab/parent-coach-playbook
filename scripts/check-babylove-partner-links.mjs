#!/usr/bin/env node
/**
 * Guard against a silent regression class: some other agent (or a manual
 * edit) quietly stripping a backlink-exchange partner's link out of a
 * BabyLoveGrowth article's body after it was imported.
 *
 * Why this exists: the Arnie affiliate agent stripped the Couch & Dumbbells
 * exchange link out of tee-ball-drills.md in commit 0700f4d while doing an
 * unrelated monetization pass, rewriting it to an internal /go/ link instead.
 * Nothing caught that until it was noticed by hand. BabyLoveGrowth's
 * exchange partners expect their placement to stay live for the exchange
 * term; a silently vanished link is a broken commitment, not a formatting
 * choice.
 *
 * Method: for every article whose frontmatter declares
 * externalSource.provider: "babylovegrowth", find the commit that first
 * added the file, read that version's body, and collect every external
 * (non-site, non-provider) markdown link URL it shipped with. Then check the
 * working tree still contains every one of those exact URLs, verbatim. This
 * only catches removal, not intentional rewording around a kept URL, and it
 * only catches links present in the very first committed version — a link
 * added later by a legitimate edit was never in scope to begin with.
 *
 * Usage:
 *   node scripts/check-babylove-partner-links.mjs            # human-readable table
 *   node scripts/check-babylove-partner-links.mjs --json      # machine-readable
 *
 * Exit 0 if every partner link from every article's first commit is still
 * present in the working tree; exit 1 otherwise.
 */

import { readFile, readdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const ARTICLES_DIR = join(root, 'src/content/articles');

const EXCLUDED_HOST_PATTERN = /(^|\.)parentcoachdesk\.com$|(^|\.)babylovegrowth\.ai$/i;
const LINK_PATTERN = /\[[^\]]*\]\((https?:\/\/[^)\s]+)\)/g;

function git(args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8' });
}

function isBabyLoveArticle(source) {
  // Deliberately a plain string check, matching the style of the existing
  // publishing-contract tests, rather than a YAML parse: frontmatter here is
  // machine-generated by buildBabyLoveArticleMarkdown and always has this
  // exact shape.
  return /^externalSource:\r?\n(?: {2}[^\n]*\r?\n?)*? {2}provider:\s*"babylovegrowth"/m.test(source);
}

function extractExternalLinks(markdown) {
  const urls = new Set();
  let match;
  LINK_PATTERN.lastIndex = 0;
  while ((match = LINK_PATTERN.exec(markdown)) !== null) {
    const url = match[1];
    let host;
    try {
      host = new URL(url).hostname;
    } catch {
      continue;
    }
    if (EXCLUDED_HOST_PATTERN.test(host)) continue;
    urls.add(url);
  }
  return urls;
}

function firstAddingCommit(relativePath) {
  const out = git(['log', '--diff-filter=A', '--format=%H', '--', relativePath]).trim();
  if (!out) return null;
  const lines = out.split('\n').filter(Boolean);
  return lines[lines.length - 1] ?? null;
}

function readAtCommit(sha, relativePath) {
  return git(['show', `${sha}:${relativePath}`]);
}

async function main() {
  const asJson = process.argv.includes('--json');
  const files = (await readdir(ARTICLES_DIR)).filter((name) => name.endsWith('.md'));

  const report = [];

  for (const name of files) {
    const relativePath = `src/content/articles/${name}`;
    const absolutePath = join(ARTICLES_DIR, name);
    const current = await readFile(absolutePath, 'utf8');
    if (!isBabyLoveArticle(current)) continue;

    const sha = firstAddingCommit(relativePath);
    if (!sha) {
      report.push({ file: relativePath, sha: null, missing: [], error: 'no adding commit found in git history' });
      continue;
    }

    let original;
    try {
      original = readAtCommit(sha, relativePath);
    } catch (error) {
      report.push({ file: relativePath, sha, missing: [], error: `could not read ${sha}: ${error.message}` });
      continue;
    }

    const originalLinks = extractExternalLinks(original);
    if (originalLinks.size === 0) continue;

    const missing = [...originalLinks].filter((url) => !current.includes(url));
    if (missing.length > 0) {
      report.push({ file: relativePath, sha, missing, error: null });
    }
  }

  const failing = report.filter((entry) => entry.missing.length > 0 || entry.error);

  if (asJson) {
    console.log(JSON.stringify({ ok: failing.length === 0, checked: files.length, failing }, null, 2));
  } else if (failing.length === 0) {
    console.log(`Partner-link guard passed: no missing exchange links across ${files.length} article files.`);
  } else {
    console.error(`Partner-link guard failed (${failing.length} file(s)):`);
    for (const entry of failing) {
      console.error(`\n${entry.file} (first added ${entry.sha ?? 'unknown'})`);
      if (entry.error) console.error(`  error: ${entry.error}`);
      for (const url of entry.missing) console.error(`  missing: ${url}`);
    }
  }

  process.exitCode = failing.length === 0 ? 0 : 1;
}

await main();
