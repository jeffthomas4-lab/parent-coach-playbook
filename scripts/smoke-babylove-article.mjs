#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROUTE = /^\/(?:drive-there|game|drive-home|team-parent)\/[a-z0-9]+(?:-[a-z0-9]+)*\/$/;

function canonicalFromHtml(html) {
  const tag = html.match(/<link\b[^>]*\brel=["']canonical["'][^>]*>/i)?.[0]
    ?? html.match(/<link\b[^>]*\bhref=["'][^"']+["'][^>]*\brel=["']canonical["'][^>]*>/i)?.[0]
    ?? '';
  return tag.match(/\bhref=["']([^"']+)["']/i)?.[1] ?? '';
}

export async function runBabyLoveArticleSmoke({ origin, canonicalOrigin, route, fetchImpl = fetch }) {
  if (!ROUTE.test(route)) throw new Error(`invalid BabyLove article route: ${route}`);
  const requestUrl = new URL(route, origin).toString();
  const expectedCanonical = new URL(route, canonicalOrigin).toString();
  const response = await fetchImpl(requestUrl, {
    redirect: 'manual',
    headers: { 'User-Agent': 'parent-coach-desk-deploy-smoke/1.0' },
    signal: AbortSignal.timeout(20_000),
  });
  const body = await response.text();
  const canonical = canonicalFromHtml(body);
  const h1 = body.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1]
    ?.replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim() ?? '';
  const checks = {
    status200: response.status === 200,
    canonicalExact: canonical === expectedCanonical,
    oneUsefulH1: h1.length >= 8 && (body.match(/<h1\b/gi) ?? []).length === 1,
    indexable: !/<meta\b[^>]*\bname=["']robots["'][^>]*\bcontent=["'][^"']*noindex/i.test(body),
    providerPromotionAbsent: !/Article generated by BabyLoveGrowth/i.test(body),
  };
  const receipt = {
    schemaVersion: 1,
    checkedAt: new Date().toISOString(),
    origin,
    route,
    requestUrl,
    status: response.status,
    canonical,
    expectedCanonical,
    h1,
    checks,
    passed: Object.values(checks).every(Boolean),
  };
  if (!receipt.passed) throw Object.assign(new Error(`BabyLove article smoke failed: ${JSON.stringify(checks)}`), { receipt });
  return receipt;
}

function readArgs(argv) {
  const value = (name) => {
    const index = argv.indexOf(name);
    return index >= 0 ? argv[index + 1] : '';
  };
  const args = {
    origin: value('--origin'),
    canonicalOrigin: value('--canonical-origin'),
    route: value('--route'),
    report: value('--report'),
  };
  if (!args.origin || !args.canonicalOrigin || !args.route || !args.report) {
    throw new Error('usage: smoke-babylove-article.mjs --origin <url> --canonical-origin <url> --route </phase/slug/> --report <json>');
  }
  return args;
}

async function main() {
  const args = readArgs(process.argv.slice(2));
  try {
    const receipt = await runBabyLoveArticleSmoke(args);
    writeFileSync(args.report, `${JSON.stringify(receipt, null, 2)}\n`, 'utf8');
    console.log(JSON.stringify(receipt));
  } catch (error) {
    const receipt = error?.receipt ?? { passed: false, error: error instanceof Error ? error.message : 'unknown' };
    writeFileSync(args.report, `${JSON.stringify(receipt, null, 2)}\n`, 'utf8');
    throw error;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
